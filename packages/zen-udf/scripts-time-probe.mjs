const rows = [];
for (const [category, expression, context, note] of probes) {
  let status;
  let result;
  try {
    const value = evaluateExpressionSync(expression, context);
    result = JSON.stringify(value);
    status = value === null || (typeof value === 'string' && value.startsWith('Invalid')) ? '⚠️ null/Invalid' : '✅';
  } catch (e) {
    status = '❌ throw';
    result = e.message.slice(0, 60);
  }
  rows.push({ category, expression, note, status, result });
  console.log(`${status}  [${category}] ${expression}  => ${result.slice(0, 50)}  (${note})`);
}
console.log('\n==== 汇总 ====');
const byStatus = {};
for (const r of rows) byStatus[r.status] = (byStatus[r.status] ?? 0) + 1;
console.log(byStatus);
